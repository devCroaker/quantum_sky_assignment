"""Write the ops team's findings report to docs/findings.md (P21).

The brief asks for a slide deck whose Findings section gives the operations
team numbers. Every number in ``docs/findings.md`` is produced here, by
loading the real committed input files and calling the same analysis the API
serves (``netscope.analysis.analyse`` for the baseline, ``netscope.criticality
.sweep`` for the full single-element sweep). Nothing is transcribed from
``CLAUDE.md``, ``docs/DECISIONS.md`` or the brief, so a change to the code or
the input data changes this document on the next run rather than silently
drifting away from it.

Follows ``scripts/export_contract.py``'s shape: a plain ``build()`` that
returns the rendered text, a ``--check`` flag that exits non-zero when the
committed file is stale, and no non-deterministic ordering anywhere, so
regenerating produces a byte-identical file.

Run with: python scripts/findings.py
Check in CI with: python scripts/findings.py --check
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Iterable, Sequence
from pathlib import Path

from netscope.analysis import ScenarioAnalysis, analyse
from netscope.criticality import (
    Assessment,
    CriticalityReason,
    CriticalitySweep,
    ElementKind,
    sweep,
)
from netscope.loaders.merge import build_network
from netscope.loaders.sites_csv import load_sites
from netscope.loaders.sndlib_xml import load_backbone
from netscope.models import Network

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "findings.md"
SNDLIB_PATH = ROOT / "data" / "nobel-eu.xml"
SITES_PATH = ROOT / "data" / "sites.csv"

#: A per-reason element list is only useful in the document when it is short.
#: Every reason in this network lists 2 to 4 elements, so the threshold does
#: not bite today. It is kept because a denser network would make one of these
#: lists long enough to be unreadable.
_MAX_LISTED_IDS = 10

#: How many links to show in the "busiest at rest" table (R10 shows five on
#: the map; the report shows twice that so the comparison with "most depended
#: upon" below has something to compare against).
_BUSIEST_SHOWN = 10


def _plural(count: int, singular: str, plural: str | None = None) -> str:
    """Render a count with the right noun.

    Written out rather than printing "piece(s)", because this document is read
    by an operations lead and quoted on a slide, and a parenthesised plural is
    the sort of thing that tells a reader a machine wrote it and nobody looked.
    """
    word = (
        singular if count == 1 else (plural if plural is not None else f"{singular}s")
    )
    return f"{count} {word}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the committed file is out of date",
    )
    args = parser.parse_args()

    rendered = render(_load_network())
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != rendered:
            print(
                f"{TARGET.relative_to(ROOT)} is out of date. Run: python scripts/findings.py",
                file=sys.stderr,
            )
            return 1
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(rendered, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


def _load_network() -> Network:
    """The real, committed inputs. Never a fixture: this report is about them."""
    backbone = load_backbone(SNDLIB_PATH)
    sites = load_sites(SITES_PATH)
    return build_network(backbone, sites, sites_file=str(SITES_PATH))


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------


def render(network: Network) -> str:
    baseline = analyse(network)
    criticality = sweep(network)

    sections = [
        _header(network),
        _question_one(network, criticality),
        _question_two(network, baseline, criticality),
        _question_three(criticality, network),
        _regenerate_note(),
    ]
    return "\n".join(sections)


def _header(network: Network) -> str:
    return (
        "# Findings\n\n"
        "Generated by `scripts/findings.py`. Every figure below is computed from the "
        "committed input files by the same analysis the API serves, not copied from a "
        "document or the brief.\n\n"
        "## Inputs\n\n"
        "The backbone topology is public research data: S. Orlowski, M. Pioro, A. "
        'Tomaszewski, R. Wessaly. "SNDlib 1.0, Survivable Network Design Library." '
        "Networks, 55(3):276-286, 2010, retrieved from "
        "<https://sndlib.put.poznan.pl/download/sndlib-networks-xml/nobel-eu.xml>. "
        "`sites.csv` is invented for this exercise, not real network data, not public data "
        "and not citable. See `data/PROVENANCE.md` for both files' checksums.\n\n"
        f"Merged network: {len(network.nodes)} nodes, {len(network.links)} links, "
        f"{len(network.demands)} demands totalling {_num(network.total_demand)} units.\n"
    )


def _question_one(network: Network, criticality: CriticalitySweep) -> str:
    nodes = _of_kind(criticality, ElementKind.NODE)
    links = _of_kind(criticality, ElementKind.LINK)

    lines = [
        "## 1. Where does the network have single points of failure?\n",
        (
            f"Of {criticality.summary.nodes_evaluated} nodes, "
            f"{criticality.summary.critical_nodes} are critical under R7. Of "
            f"{criticality.summary.links_evaluated} links, "
            f"{criticality.summary.critical_links} are critical.\n"
        ),
        "### Breakdown by reason\n",
        "| Reason | Nodes | Node ids | Links | Link ids |",
        "|---|---|---|---|---|",
    ]
    for reason in CriticalityReason:
        node_ids = _ids_with(nodes, reason)
        link_ids = _ids_with(links, reason)
        lines.append(
            f"| `{reason.value}` | {len(node_ids)} | {_listed(node_ids)} | "
            f"{len(link_ids)} | {_listed(link_ids)} |"
        )
    lines.append("")

    structural_nodes = _structural_ids(nodes)
    structural_links = _structural_ids(links)

    lines.extend(
        [
            "### What counts as critical, and what does not\n",
            (
                f"**{criticality.summary.critical_nodes} of "
                f"{criticality.summary.nodes_evaluated} nodes and "
                f"{criticality.summary.critical_links} of "
                f"{criticality.summary.links_evaluated} links are critical.** An "
                "element is critical when losing it costs somebody else something: "
                "it partitions the surviving graph, it strands a demand between two "
                "nodes that are both still there, or it drives a surviving link over "
                "capacity.\n"
            ),
            (
                "Traffic that a failed node was itself sending or receiving is "
                "reported separately, in the endpoint-affected figures, because R8 "
                "requires that. It does not make the node critical. An earlier "
                "version of this analysis counted it, which is the literal text of "
                "R7b, and the result was that every node originating any traffic was "
                "critical: 37 of 37 here. That number could not be lower whatever the "
                "network looked like, so it described the demand matrix rather than "
                "the network, and it was reverted (`docs/DECISIONS.md` D24).\n"
            ),
            (
                "The elements whose loss breaks something structurally, as opposed to "
                "overloading a link:\n"
            ),
            f"- **Nodes** ({len(structural_nodes)}): {_listed(structural_nodes, limit=None)}",
            f"- **Links** ({len(structural_links)}): {_listed(structural_links, limit=None)}\n",
            (
                "The remaining critical elements are the ones that overload a "
                "surviving link rather than cutting anything off. They matter for a "
                "different reason: nothing is unreachable, but a link is carrying "
                "more than it can.\n"
            ),
        ]
    )

    lines.append(_warsaw_paragraph(nodes))
    return "\n".join(lines)


def _warsaw_paragraph(nodes: Sequence[Assessment]) -> str:
    warsaw = _by_id(nodes, "Warsaw")
    return (
        "### Warsaw: the case a connectivity check gets wrong\n\n"
        f"`Warsaw` partitions nothing: losing it leaves the graph in "
        f"{_plural(warsaw.impact.components, 'piece')}. It is still critical, because "
        "`OPS-EAST-2` "
        "attaches to both `HUB-EAST` and `Budapest` and so accidentally dual-homes the "
        "aggregation hub, and `OPS-EAST-2` is an operations site that may not forward "
        "traffic under R6. With `Warsaw` gone, the hub's own "
        f"{warsaw.impact.undeliverable_demands} demands ({_num(warsaw.impact.undeliverable_units)} "
        "units) have no legal path even though the graph is still in one piece. A "
        "connectivity check alone would call this network more resilient than it is.\n"
    )


def _question_two(
    network: Network, baseline: ScenarioAnalysis, criticality: CriticalitySweep
) -> str:
    busiest = sorted(
        baseline.link_utilizations, key=lambda e: (-e.utilization, e.link_id)
    )[:_BUSIEST_SHOWN]
    link_assessments = [
        a
        for a in _of_kind(criticality, ElementKind.LINK)
        if a.impact.undeliverable_demands > 0 or a.impact.overloaded_links > 0
    ]
    depended = sorted(
        link_assessments,
        key=lambda a: (-a.impact.undeliverable_units, -a.impact.overloaded_links, a.id),
    )

    busiest_ids = {entry.link_id for entry in busiest}
    depended_ids = {a.id for a in depended}
    both = sorted(busiest_ids & depended_ids)
    busiest_only = sorted(busiest_ids - depended_ids)
    depended_only = sorted(depended_ids - busiest_ids)

    lines = [
        "## 2. Which links does the traffic depend on most?\n",
        "### Busiest at rest\n",
        f"The {len(busiest)} most utilized links in the baseline, no failures applied.\n",
        "| Rank | Link | Endpoints | Load | Capacity | Utilization |",
        "|---|---|---|---|---|---|",
    ]
    for rank, entry in enumerate(busiest, start=1):
        endpoints = network.links[entry.link_id].endpoints
        lines.append(
            f"| {rank} | `{entry.link_id}` | {endpoints} | {_num(entry.load)} | "
            f"{_num(entry.capacity)} | {_pct(entry.utilization)} |"
        )
    lines.append("")

    lines.extend(
        [
            "### Most depended upon\n",
            (
                "Every link ranked by the damage its own loss causes: demands and "
                "units left undeliverable, and how many surviving links that failure "
                "pushes over 100%. Only links with non-zero damage are listed; the "
                f"other {len(network.links) - len(depended)} links strand nothing and "
                "overload nothing when they themselves fail.\n"
            ),
            (
                "| Rank | Link | Endpoints | Demands lost | Units lost | Links driven "
                "over 100% | Peak utilization caused |"
            ),
            "|---|---|---|---|---|---|---|",
        ]
    )
    for rank, assessment in enumerate(depended, start=1):
        endpoints = network.links[assessment.id].endpoints
        lines.append(
            f"| {rank} | `{assessment.id}` | {endpoints} | "
            f"{assessment.impact.undeliverable_demands} | "
            f"{_num(assessment.impact.undeliverable_units)} | "
            f"{assessment.impact.overloaded_links} | "
            f"{_pct(assessment.impact.max_utilization)} |"
        )
    lines.append("")

    lines.extend(
        [
            "### How the two lists differ\n",
            f"- On both lists: {_listed(tuple(both), limit=None)}",
            (
                "- Busiest at rest only (never strands a demand or causes an "
                f"overload if it fails itself): "
                f"{_listed(tuple(busiest_only), limit=None)}"
            ),
            (
                f"- Most depended upon only (not among the {len(busiest)} busiest "
                "at baseline, but costly to lose): "
                f"{_listed(tuple(depended_only), limit=None)}\n"
            ),
            (
                "A link can carry a lot of traffic today and still be safe to lose, "
                "if the network has somewhere else to put that traffic. The reverse "
                "also holds: a lightly loaded access link can be a single point of "
                "failure for the one site behind it.\n"
            ),
        ]
    )
    return "\n".join(lines)


def _question_three(criticality: CriticalitySweep, network: Network) -> str:
    total = criticality.summary.nodes_evaluated + criticality.summary.links_evaluated
    stranding = sorted(
        (a for a in criticality.assessments if a.impact.undeliverable_demands > 0),
        key=lambda a: (a.kind.value, a.id),
    )
    overloading = sorted(
        (a for a in criticality.assessments if a.impact.overloaded_links > 0),
        key=lambda a: (-a.impact.max_utilization, a.kind.value, a.id),
    )

    victims = _victim_tally(network, overloading)
    worst_victim, worst_count = max(
        victims.items(), key=lambda item: (item[1], item[0])
    )

    lines = [
        "## 3. What happens when a given link or site goes down?\n",
        (
            f"The sweep covers all {total} single-element failures "
            f"({criticality.summary.nodes_evaluated} nodes plus "
            f"{criticality.summary.links_evaluated} links). {len(stranding)} of them "
            "strand at least one demand between two surviving nodes. Only "
            f"{len(overloading)} push any surviving link over 100% utilization, "
            "which is the rare case R7c is written for.\n"
        ),
        "### Failures that strand a demand\n",
        (
            f"All {len(stranding)} cases strand exactly "
            f"{_plural(stranding[0].impact.undeliverable_demands if stranding else 0, 'demand')}"
            " for "
            f"{_num(stranding[0].impact.undeliverable_units) if stranding else '0'} "
            "units; this is the same structural set named in question 1.\n"
        ),
        "| Element | Kind | Demands lost | Units lost |",
        "|---|---|---|---|",
    ]
    for a in stranding:
        lines.append(
            f"| `{a.id}` | {a.kind.value} | {a.impact.undeliverable_demands} | "
            f"{_num(a.impact.undeliverable_units)} |"
        )
    lines.append("")

    lines.extend(
        [
            "### Failures that overload a link\n",
            (
                f"Only {len(overloading)} of {total} single failures overload "
                "anything. Worst first, by the peak utilization the failure "
                "causes:\n"
            ),
            "| Element | Kind | Links overloaded | Peak utilization caused |",
            "|---|---|---|---|",
        ]
    )
    for a in overloading:
        lines.append(
            f"| `{a.id}` | {a.kind.value} | {a.impact.overloaded_links} | "
            f"{_pct(a.impact.max_utilization)} |"
        )
    lines.append("")

    lines.append(
        f"`{worst_victim}` is the link that keeps appearing as the victim: it is pushed over "
        f"100% in {worst_count} of the {len(overloading)} overload-causing failures above.\n"
    )
    return "\n".join(lines)


def _victim_tally(
    network: Network, overloading: Iterable[Assessment]
) -> dict[str, int]:
    """How often each surviving link is the one driven over 100%.

    Re-runs ``analyse`` for the handful of failures that overload anything,
    because ``FailureImpact`` only carries the count, not which link it was.
    There are at most a few of these on this network (four, measured), so a
    second pass here costs nothing next to the 92-scenario sweep itself.
    """
    tally: dict[str, int] = {}
    for assessment in overloading:
        if assessment.kind is ElementKind.NODE:
            result = analyse(network, failed_nodes=frozenset({assessment.id}))
        else:
            result = analyse(network, failed_links=frozenset({assessment.id}))
        for entry in result.overloaded:
            tally[entry.link_id] = tally.get(entry.link_id, 0) + 1
    return tally


def _regenerate_note() -> str:
    return (
        "## How to regenerate\n\n"
        "```\n"
        "python scripts/findings.py\n"
        "```\n\n"
        "Run with `--check` to verify the committed file is still current without "
        "rewriting it.\n"
    )


# ---------------------------------------------------------------------------
# Small shared helpers
# ---------------------------------------------------------------------------


def _of_kind(
    criticality: CriticalitySweep, kind: ElementKind
) -> tuple[Assessment, ...]:
    return tuple(a for a in criticality.assessments if a.kind is kind)


def _by_id(assessments: Sequence[Assessment], element_id: str) -> Assessment:
    for assessment in assessments:
        if assessment.id == element_id:
            return assessment
    raise KeyError(element_id)


def _ids_with(
    assessments: Sequence[Assessment], reason: CriticalityReason
) -> tuple[str, ...]:
    return tuple(sorted(a.id for a in assessments if reason in a.reasons))


def _structural_ids(assessments: Sequence[Assessment]) -> tuple[str, ...]:
    structural = {
        CriticalityReason.PARTITIONS_NETWORK,
        CriticalityReason.DEMANDS_UNDELIVERABLE,
    }
    return tuple(
        sorted(a.id for a in assessments if structural.intersection(a.reasons))
    )


def _listed(ids: tuple[str, ...], *, limit: int | None = _MAX_LISTED_IDS) -> str:
    if not ids:
        return "none"
    if limit is not None and len(ids) > limit:
        return f"{len(ids)} elements, too many to list usefully here"
    return ", ".join(f"`{element_id}`" for element_id in ids)


def _num(value: float) -> str:
    """Full precision, matching how the value is actually stored.

    A rounded load has already caused one error in this project (see
    `CLAUDE.md`), so this prints whatever ``repr``-equivalent ``str`` gives a
    float, which is the shortest decimal that reads back to the same value.
    """
    return str(value)


def _pct(fraction: float) -> str:
    """A percentage to two decimal places, stated so the precision is explicit."""
    return f"{fraction * 100:.2f}%"


